/* Initial bounded WS-Print implementation for one-document jobs.
 * Does not transcode, prepend PJL, or interpret the captured HP PCL XL.
 * The RAW printer daemon owns/serializes the USB device. */
static void fail(const char *status,const char *msg){
    printf("Status: %s\r\nContent-Type: text/plain\r\nContent-Length: %zu\r\n\r\n%s",
           status,strlen(msg),msg);
}
static int decimal_element(const char *soap,const char *name,long *val){
    const char *p=strstr(soap,name),*q;char *end;long x;
    if(!p)return -1;
    p=strchr(p,'>');if(!p)return -1;p++;
    errno=0;x=strtol(p,&end,10);
    if(errno||p==end||x<1||x>2147483647)return -1;
    q=end;while(*q==' '||*q=='\r'||*q=='\n')q++;
    if(*q!='<')return -1;
    *val=x;return 0;
}
static int jobfile(long id,char *out,size_t cap){
    int k=snprintf(out,cap,"/tmp/minibox-wsd-job-%ld",id);
    return k>0&&(size_t)k<cap?0:-1;
}
static int boundary_of(const char *ct,char *out,size_t cap){
    const char *p,*e;size_t n;
    if(!ct||!strstr(ct,"multipart/related"))return -1;
    p=strstr(ct,"boundary=");if(!p)return -1;p+=9;
    if(*p=='"'){p++;e=strchr(p,'"');}
    else{e=p;while(*e&&*e!=';'&&*e!=' '&&*e!='\r')e++;}
    if(!e)return -1;n=(size_t)(e-p);
    if(!n||n>=cap)return -1;
    memcpy(out,p,n);out[n]=0;return 0;
}
static int soap_and_cid(const unsigned char *body,size_t len,const char *boundary,
                        char *soap,size_t cap,char *cid,size_t cidcap){
    /* The root SOAP MIME part starts with the first boundary. We limit
     * parsing to the beginning of that part; print data is binary opaque. */
    char sep[160];const unsigned char *start,*end,*p,*q;size_t k,span;
    k=(size_t)snprintf(sep,sizeof sep,"\r\n--%s",boundary);
    if(k>=sizeof sep||len<10)return -1;
    p=(const unsigned char *)strstr((const char *)"", "");(void)p;
    start=0;
    for(size_t i=0;i+3<len && i<8192;i++)
        if(!memcmp(body+i,"\r\n\r\n",4)){start=body+i+4;break;}
    if(!start)return -1;
    end=0;
    for(size_t i=(size_t)(start-body);i+k<=len&&i-(size_t)(start-body)<65536;i++)
        if(!memcmp(body+i,sep,k)){end=body+i;break;}
    if(!end)return -1;
    span=(size_t)(end-start);
    if(!span||span>=cap)return -1;
    memcpy(soap,start,span);soap[span]=0;
    q=(const unsigned char *)strstr(soap,"href=\"cid:");
    if(!q)return -1;
    q+=10;p=(const unsigned char *)strchr((const char *)q,'"');
    if(!p||p==q||(size_t)(p-q)>=cidcap)return -1;
    memcpy(cid,q,(size_t)(p-q));cid[p-q]=0;
    return 0;
}
static void soap_reply(const char *action,const char *request_id,
                       const char *reply_id,const char *body){
    char output[2048];int k;
    /* IDs are generated by us or extracted from WS-Addressing; require URN
     * UUID values before interpolating into the XML response. */
    if(strncmp(request_id,"urn:uuid:",9) || strncmp(reply_id,"urn:uuid:",9)){
        fail("400 Bad Request","Invalid message identifier\n");return;
    }
    for(const char *p=request_id;*p;p++)
        if(!((*p>='a'&&*p<='z')||(*p>='A'&&*p<='Z')||
             (*p>='0'&&*p<='9')||*p==':'||*p=='-')){
            fail("400 Bad Request","Invalid message identifier\n");return;
        }
    k=snprintf(output,sizeof output,
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>"
        "<s:Envelope xmlns:s=\"http://www.w3.org/2003/05/soap-envelope\" "
        "xmlns:a=\"http://schemas.xmlsoap.org/ws/2004/08/addressing\" "
        "xmlns:wprt=\"http://schemas.microsoft.com/windows/2005/05/wdp/print\">"
        "<s:Header><a:To>http://schemas.xmlsoap.org/ws/2004/08/addressing/role/anonymous</a:To>"
        "<a:Action>http://schemas.microsoft.com/windows/2005/05/wdp/print/%sResponse</a:Action>"
        "<a:MessageID>%s</a:MessageID><a:RelatesTo>%s</a:RelatesTo></s:Header>"
        "<s:Body><wprt:%sResponse>%s</wprt:%sResponse></s:Body></s:Envelope>",
        action,reply_id,request_id,action,body,action);
    if(k<=0||(size_t)k>=sizeof output){fail("500 Internal Server Error","SOAP response too large\n");return;}
    printf("Status: 200 OK\r\nContent-Type: application/soap+xml; charset=utf-8\r\n"
           "Content-Length: %d\r\nCache-Control: no-store\r\n\r\n",k);
    fwrite(output,1,(size_t)k,stdout);
}
int mb_wsd_print_operation(enum mb_wsd_http_action kind,
                           const unsigned char *body,size_t len,
                           const char *ct,const char *request_id,const char *reply_id){
    char path[90],payload[64],boundary[128],cid[220],soap[65536];long id;
    int fd;
    if(kind==MB_WSD_HTTP_CREATE_PRINT_JOB){
        struct timespec ts;
        /* Keep job ID unique across separate CGI processes. */
        if(clock_gettime(CLOCK_REALTIME,&ts)){fail("503 Service Unavailable","Clock unavailable\n");return 0;}
        for(int attempt=0;attempt<16;attempt++){
            unsigned long mix=(unsigned long)ts.tv_sec*1000003UL+
                              (unsigned long)ts.tv_nsec+(unsigned long)getpid()+attempt;
            id=(long)(mix%2000000000UL)+1;
            if(jobfile(id,path,sizeof path))break;
            fd=open(path,O_CREAT|O_EXCL|O_WRONLY,0600);
            if(fd>=0){close(fd);
                snprintf(payload,sizeof payload,"<wprt:JobId>%ld</wprt:JobId>",id);
                soap_reply("CreatePrintJob",request_id,reply_id,payload);return 0;
            }
            if(errno!=EEXIST)break;
        }
        fail("503 Service Unavailable","Cannot allocate WSD job\n");return 0;
    }
    if(kind!=MB_WSD_HTTP_SEND_DOCUMENT){fail("501 Not Implemented","Unknown operation\n");return 0;}
    if(boundary_of(ct,boundary,sizeof boundary)||
       soap_and_cid(body,len,boundary,soap,sizeof soap,cid,sizeof cid)||
       !strstr(soap,"SendDocumentRequest")||
       decimal_element(soap,"JobId",&id)||
       jobfile(id,path,sizeof path)){
        fail("400 Bad Request","Invalid SendDocument MTOM request\n");return 0;
    }
    fd=open(path,O_RDONLY|O_NOFOLLOW);
    if(fd<0){fail("404 Not Found","WSD job not found\n");return 0;}
    close(fd);
    {
        const unsigned char *bytes;size_t size;
        if(mb_wsd_mtom_attachment(body,len,boundary,cid,&bytes,&size)||!size){
            fail("400 Bad Request","Missing binary document attachment\n");return 0;
        }
        /* One document per job; only acknowledge after RAW transport accepted
         * all bytes. RAW socket acknowledgment is not physical print proof. */
        if(mb_wsd_raw_submit(bytes,size,9100)){
            fail("503 Service Unavailable","RAW USB transport failed\n");return 0;
        }
        unlink(path);
        soap_reply("SendDocument",request_id,reply_id,"");
    }
    return 0;
}
